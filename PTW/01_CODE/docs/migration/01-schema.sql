-- ---------------------------------------------------------------------
-- C. Khóa ngoại (tách riêng để import dữ liệu không bị chặn thứ tự)
-- ---------------------------------------------------------------------

ALTER TABLE public.heritage_content ADD CONSTRAINT heritage_content_location_id_fkey
  FOREIGN KEY (location_id) REFERENCES public.locations(id) ON DELETE CASCADE;

ALTER TABLE public.contributions ADD CONSTRAINT contributions_location_id_fkey
  FOREIGN KEY (location_id) REFERENCES public.locations(id) ON DELETE SET NULL;

ALTER TABLE public.sellers ADD CONSTRAINT sellers_location_id_fkey
  FOREIGN KEY (location_id) REFERENCES public.locations(id) ON DELETE SET NULL;

ALTER TABLE public.product_items ADD CONSTRAINT product_items_category_id_fkey
  FOREIGN KEY (category_id) REFERENCES public.product_categories(id);

ALTER TABLE public.product_variants ADD CONSTRAINT product_variants_product_id_fkey
  FOREIGN KEY (product_id) REFERENCES public.product_items(id) ON DELETE CASCADE;

ALTER TABLE public.product_skus ADD CONSTRAINT product_skus_product_id_fkey
  FOREIGN KEY (product_id) REFERENCES public.product_items(id) ON DELETE CASCADE;

ALTER TABLE public.product_custom_values ADD CONSTRAINT product_custom_values_product_id_fkey
  FOREIGN KEY (product_id) REFERENCES public.product_items(id) ON DELETE CASCADE;

ALTER TABLE public.product_custom_values ADD CONSTRAINT product_custom_values_field_id_fkey
  FOREIGN KEY (field_id) REFERENCES public.product_custom_fields(id) ON DELETE CASCADE;

ALTER TABLE public.order_items ADD CONSTRAINT order_items_order_id_fkey
  FOREIGN KEY (order_id) REFERENCES public.order_headers(id);

